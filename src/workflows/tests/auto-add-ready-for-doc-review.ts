import fs from 'node:fs'
import { runInNewContext } from 'node:vm'

import { load } from 'js-yaml'
import { describe, expect, test } from 'vitest'

const workflow = load(
  fs.readFileSync('.github/workflows/auto-add-ready-for-doc-review.yml', 'utf8'),
) as {
  on: { pull_request: { types: string[] } }
  jobs: { 'add-review-label': { if: string } }
}

interface PullRequestContext {
  body?: string | null
  author?: string
  actor?: string
  draft?: boolean
  repository?: string
}

function shouldRun(action: string, context: PullRequestContext) {
  return runInNewContext(workflow.jobs['add-review-label'].if, {
    github: {
      repository: context.repository ?? 'github/docs-internal',
      actor: context.actor ?? context.author ?? 'contributor',
      event: {
        action,
        pull_request: {
          body: context.body,
          draft: context.draft ?? false,
          user: { login: context.author ?? 'contributor' },
        },
      },
    },
    contains: (value: string | null | undefined, search: string) =>
      (value ?? '').toLowerCase().includes(search.toLowerCase()),
  })
}

describe('auto-add ready-for-doc-review', () => {
  test('handles opened and ready_for_review events', () => {
    expect(workflow.on.pull_request.types).toEqual(['opened', 'ready_for_review'])
  })

  describe.each(['opened', 'ready_for_review'])('%s', (action) => {
    test.each<{ name: string; context: PullRequestContext; expected: boolean }>([
      {
        name: 'excludes Doc It PRs from the current Copilot identity',
        context: {
          author: 'Copilot',
          body: 'Summary\n\nThis pull request was generated by Doc It v2.\n\nDetails',
        },
        expected: false,
      },
      {
        name: 'excludes Doc It PRs from the legacy Copilot identity',
        context: {
          author: 'copilot-swe-agent[bot]',
          body: 'This pull request was generated by Doc It v2',
        },
        expected: false,
      },
      {
        name: 'excludes Doc It PRs promoted by a human',
        context: {
          author: 'Copilot',
          actor: 'contributor',
          body: 'This pull request was generated by Doc It v2',
        },
        expected: false,
      },
      {
        name: 'keeps ordinary human PRs',
        context: { body: 'Update the documentation' },
        expected: true,
      },
      {
        name: 'keeps unrelated Copilot PRs',
        context: { author: 'Copilot', body: 'Update the documentation' },
        expected: true,
      },
      {
        name: 'keeps unrelated legacy Copilot PRs',
        context: { author: 'copilot-swe-agent[bot]', body: 'Update the documentation' },
        expected: true,
      },
      {
        name: 'keeps PRs mentioning Doc It without the provenance marker',
        context: { body: 'Document the Doc It v2 workflow' },
        expected: true,
      },
      { name: 'keeps null bodies', context: { body: null }, expected: true },
      { name: 'keeps missing bodies', context: {}, expected: true },
      { name: 'keeps empty bodies', context: { body: '' }, expected: true },
      { name: 'excludes drafts', context: { draft: true }, expected: false },
      {
        name: 'excludes the public repository',
        context: { repository: 'github/docs' },
        expected: false,
      },
      {
        name: 'excludes github-openapi-bot',
        context: { actor: 'github-openapi-bot' },
        expected: false,
      },
      { name: 'excludes docs-bot', context: { actor: 'docs-bot' }, expected: false },
    ])('$name', ({ context, expected }) => {
      expect(shouldRun(action, context)).toBe(expected)
    })
  })
})
