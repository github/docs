import type { Context, Page } from '@/types'
import type { LinkData, PageTransformer } from './types'
import { renderLiquid } from '@/content-render/liquid/index'
import { loadTemplate } from '@/article-api/lib/load-template'
import { resolvePath } from '@/article-api/lib/resolve-path'
import { getLinkData } from '@/article-api/lib/get-link-data'
import { stripHtmlCommentsAndNormalizeWhitespace } from '@/article-api/lib/strip-html-comments'

interface CodeQLCliPage extends Page {
  children?: string[]
}

export class CodeQLCliTransformer implements PageTransformer {
  templateName = 'codeql-cli-page.template.md'

  canTransform(page: Page): boolean {
    return page.autogenerated === 'codeql-cli'
  }

  async transform(page: Page, pathname: string, context: Context): Promise<string> {
    // Fully generated CodeQL CLI pages need markdownRequested=true to render markdown output.
    context.markdownRequested = true
    const content = await page.render(context)

    const intro = page.intro ? await page.renderProp('intro', context, { textOnly: true }) : ''

    // The manual index has a body note and child command pages, so keep both like the HTML TOC page.
    const children = (page as CodeQLCliPage).children || []
    const languageCode = page.languageCode || 'en'
    const childLinks = await Promise.all(
      children.map((href) => getLinkData(href, languageCode, pathname, context, resolvePath)),
    )
    const links = childLinks.filter((link): link is LinkData => link !== null && Boolean(link.href))

    const templateData: Record<string, unknown> = {
      page: {
        title: page.title,
        intro,
      },
      content,
      links,
    }

    const templateContent = loadTemplate(this.templateName)

    // page.render already rewrote local links, and a second rewrite pass re-versions pinned links.
    const result = await renderLiquid(templateContent, { ...context, ...templateData })

    // Strip markdownlint-disable and any other HTML comments.
    return stripHtmlCommentsAndNormalizeWhitespace(result)
  }
}
