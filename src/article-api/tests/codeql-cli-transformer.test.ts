import { describe, expect, test, vi } from 'vitest'

import { transformerRegistry } from '@/article-api/transformers/index'
import { CodeQLCliTransformer } from '@/article-api/transformers/codeql-cli-transformer'
import type { Context, Page } from '@/types'

vi.mock('@/article-api/lib/get-link-data', () => ({
  getLinkData: async (href: string) => ({
    href: `/en/code-security/codeql-cli/codeql-cli-manual${href}`,
    title: href.slice(1),
    intro: '',
  }),
}))

const versionNote = '> [!NOTE]\n> This content describes the most recent release of the CodeQL CLI.'

const manualIndexPage = {
  autogenerated: 'codeql-cli',
  relativePath: 'code-security/reference/code-scanning/codeql/codeql-cli-manual/index.md',
  documentType: 'subcategory',
  title: 'CodeQL CLI commands manual',
  intro: '',
  languageCode: 'en',
  children: ['/bqrs-decode', '/database-analyze'],
  render: async () => versionNote,
  renderProp: async () => '',
} as unknown as Page

const commandPage = {
  autogenerated: 'codeql-cli',
  relativePath:
    'code-security/reference/code-scanning/codeql/codeql-cli-manual/database-analyze.md',
  documentType: 'article',
  title: 'database analyze',
  intro: '',
  languageCode: 'en',
  render: async () => '## Synopsis',
  renderProp: async () => '',
} as unknown as Page

describe('CodeQLCliTransformer', () => {
  const transformer = new CodeQLCliTransformer()

  test('registry routes the manual index and command pages to CodeQLCliTransformer', () => {
    expect(transformerRegistry.findTransformer(manualIndexPage)).toBeInstanceOf(
      CodeQLCliTransformer,
    )
    expect(transformerRegistry.findTransformer(commandPage)).toBeInstanceOf(CodeQLCliTransformer)
  })

  test('manual index keeps the body note and lists command links', async () => {
    const result = await transformer.transform(manualIndexPage, '/en/manual', {} as Context)

    expect(result).toContain('# CodeQL CLI commands manual')
    expect(result).toContain('This content describes the most recent release of the CodeQL CLI.')
    expect(result).toContain('## Links')
    expect(result).toContain(
      '* [bqrs-decode](/en/code-security/codeql-cli/codeql-cli-manual/bqrs-decode)',
    )
    expect(result).toContain(
      '* [database-analyze](/en/code-security/codeql-cli/codeql-cli-manual/database-analyze)',
    )
  })

  test('command pages have no links section', async () => {
    const result = await transformer.transform(
      commandPage,
      '/en/manual/database-analyze',
      {} as Context,
    )

    expect(result).toContain('## Synopsis')
    expect(result).not.toContain('## Links')
  })
})
