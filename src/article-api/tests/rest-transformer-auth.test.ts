import { describe, expect, test, vi } from 'vitest'

import { RestTransformer } from '@/article-api/transformers/rest-transformer'
import getRest from '@/rest/lib/index'
import { allVersions } from '@/versions/lib/all-versions'
import type { CodeSample, Operation } from '@/rest/components/types'
import type { Context, Page } from '@/types'

vi.mock('@/rest/lib/index', () => ({ default: vi.fn() }))

const stubPage = {
  autogenerated: 'rest',
  relativePath: 'rest/apps/oauth-applications.md',
  title: 'OAuth authorizations',
  intro: '',
  markdown: '',
  renderProp: vi.fn().mockResolvedValue(''),
} as unknown as Page

const context = {
  currentVersion: 'free-pro-team@latest',
  currentVersionObj: allVersions['free-pro-team@latest'],
  allVersions,
} as unknown as Context

const makeOperation = (title: string, requestPath: string, basicAuth: boolean): Operation =>
  ({
    serverUrl: 'https://api.github.com',
    verb: 'post',
    title,
    requestPath,
    descriptionHTML: '',
    category: 'apps',
    subcategory: 'oauth-applications',
    statusCodes: [],
    bodyParameters: [],
    parameters: [],
    progAccess: { permissions: [], ...(basicAuth ? { basicAuth: true } : {}) },
    codeExamples: [
      {
        request: { description: 'Example', acceptHeader: 'application/vnd.github.v3+json' },
        response: { statusCode: '200' },
      } as unknown as CodeSample,
    ],
  }) as unknown as Operation

async function renderSections() {
  vi.mocked(getRest).mockResolvedValue({
    'oauth-applications': [
      makeOperation('Check a token', '/applications/CLIENT_ID/token', true),
      makeOperation('Create a thing', '/things', false),
    ],
  } as never)
  const body = await new RestTransformer().transform(
    stubPage,
    '/en/rest/apps/oauth-applications',
    context,
  )
  const [, basicAuthSection, otherSection] = body.split(/^## /m)
  return { basicAuthSection, otherSection }
}

describe('RestTransformer basic authentication', () => {
  test('adds Basic auth credentials to the curl example for basicAuth operations', async () => {
    const { basicAuthSection, otherSection } = await renderSections()

    expect(basicAuthSection).toContain(
      'https://api.github.com/applications/CLIENT_ID/token \\\n  -u "<YOUR_CLIENT_ID>:<YOUR_CLIENT_SECRET>"',
    )
    expect(otherSection).not.toContain('-u "')
  })

  test('adds a Basic authentication note to basicAuth operations', async () => {
    const { basicAuthSection, otherSection } = await renderSections()

    expect(basicAuthSection).toContain('Basic authentication')
    expect(basicAuthSection).toContain('`client_id`')
    expect(basicAuthSection).toContain('`client_secret`')
    expect(basicAuthSection).toContain('Do not send an `Authorization: Bearer` header')
    expect(otherSection).not.toContain('Do not send an `Authorization: Bearer` header')
    expect(otherSection).not.toContain('Basic authentication')
    expect(otherSection).not.toContain('client_secret')
  })
})
