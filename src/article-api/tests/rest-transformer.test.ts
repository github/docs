import { describe, expect, test, vi } from 'vitest'

import { RestTransformer } from '@/article-api/transformers/rest-transformer'
import getRest from '@/rest/lib/index'
import { allVersions } from '@/versions/lib/all-versions'
import type { CodeSample, Operation } from '@/rest/components/types'
import type { Context, Page } from '@/types'

vi.mock('@/rest/lib/index', () => ({ default: vi.fn() }))

const stubPage = {
  autogenerated: 'rest',
  relativePath: 'rest/example/example.md',
  title: 'Example',
  intro: '',
  markdown: '',
  renderProp: vi.fn().mockResolvedValue(''),
} as unknown as Page

const context = {
  currentVersion: 'free-pro-team@latest',
  currentVersionObj: allVersions['free-pro-team@latest'],
  allVersions,
} as unknown as Context

const makeExample = (contentType: string, example: Record<string, string> = {}): CodeSample =>
  ({
    request: {
      description: `Example ${contentType}`,
      acceptHeader: 'application/vnd.github.v3+json',
      parameters: { ref: 'REF' },
    },
    response: { statusCode: '200', contentType, example },
  }) as unknown as CodeSample

const makeOperation = (overrides: Partial<Operation>): Operation =>
  ({
    serverUrl: 'https://api.github.com',
    verb: 'get',
    title: 'Example',
    descriptionHTML: '',
    category: 'example',
    subcategory: 'example',
    statusCodes: [],
    bodyParameters: [],
    parameters: [],
    codeExamples: [],
    ...overrides,
  }) as Operation

const queryParam = (name: string) => ({
  name,
  in: 'query',
  required: true,
  description: '',
  schema: { type: 'string' },
})

async function render(operations: Operation[]) {
  vi.mocked(getRest).mockResolvedValue({ example: operations } as never)
  return new RestTransformer().transform(stubPage, '/en/rest/example/example', context)
}

describe('RestTransformer code examples', () => {
  test('uses the response media type as the Accept header', async () => {
    const body = await render([
      makeOperation({
        title: 'Get a commit',
        requestPath: '/repos/{ref}/commits',
        codeExamples: [
          makeExample('application/json'),
          makeExample('application/vnd.github.diff'),
          makeExample('application/vnd.github.sha'),
        ],
      }),
    ])

    expect(body).toContain('-H "Accept: application/vnd.github.diff"')
    expect(body).toContain('-H "Accept: application/vnd.github.sha"')
    expect(body).not.toContain('-H "Accept: application/json"')
    expect(body).not.toContain('-H "Accept: application/vnd.github+json"')
  })

  test('appends required query parameters and quotes the URL', async () => {
    const body = await render([
      makeOperation({
        title: 'Search code',
        requestPath: '/search/code',
        parameters: [queryParam('q')],
        codeExamples: [makeExample('application/json')],
      }),
      makeOperation({
        title: 'Search labels',
        requestPath: '/search/labels',
        parameters: [queryParam('repository_id'), queryParam('q')],
        codeExamples: [makeExample('application/json', { repository_id: '42' })],
      }),
    ])

    expect(body).toContain('"https://api.github.com/search/code?q=Q"')
    expect(body).toContain('"https://api.github.com/search/labels?repository_id=42&q=Q"')
  })

  test('leaves URLs without a query string unquoted', async () => {
    const body = await render([
      makeOperation({
        requestPath: '/repos/{ref}/commits',
        codeExamples: [makeExample('application/json')],
      }),
    ])

    expect(body).toContain('  https://api.github.com/repos/REF/commits\n')
  })
})
