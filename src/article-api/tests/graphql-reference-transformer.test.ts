const stubPage = {
  autogenerated: 'graphql',
  relativePath: 'graphql/reference/repos.md',
  title: 'Widgets',
  intro: '',
  renderProp: vi.fn().mockResolvedValue(''),
} as unknown as Page

const context = { currentVersion: 'free-pro-team@latest' } as Context

describe('GraphQLReferenceTransformer default values', () => {
  test('renders true and false defaults and skips missing ones', async () => {
    const transformer = new GraphQLReferenceTransformer()
    const output = await transformer.transform(stubPage, '/en/graphql/reference/repos', context)
    const lines = output.split('\n')
    const lineFor = (prefix: string) => lines.find((line) => line.includes(prefix)) ?? ''

    expect(lineFor('`followRenames` (Boolean)')).toContain('Default: `true`.')
    expect(lineFor('`dryRun` (Boolean)')).toContain('Default: `false`.')
    expect(lineFor('`owner` (String!)')).not.toContain('Default:')
    expect(lineFor('`orderBy` (WidgetOrder)')).toContain(
      'Default: `{field: UPDATED_AT, direction: DESC}`.',
    )

    expect(lineFor('`includeHidden` (Boolean)')).toContain('Default: `false`.')
    expect(lineFor('`includeVisible` (Boolean)')).toContain('Default: `true`.')
    expect(lineFor('`label` (String)')).not.toContain('Default:')

    expect(lineFor('`archived` (Boolean)')).toContain('Default: `false`.')
  })
})
