import { describe, expect, test, vi } from 'vitest'

import { CodeQLCliTransformer } from '@/article-api/transformers/codeql-cli-transformer'
import { latest } from '@/versions/lib/enterprise-server-releases'
import type { Context, Page } from '@/types'

// page.render already rewrote this link to its final /<lang>/<version>/ form.
const ghesHref = `/en/enterprise-server@${latest}/code-security/reference/code-scanning/sarif-files/sarif-support`
const renderedBody = `## Description\n\nSee [SARIF support for GHES](${ghesHref}).`

const stubPage = {
  autogenerated: 'codeql-cli',
  title: 'github upload-results',
  intro: '',
  render: vi.fn().mockResolvedValue(renderedBody),
  renderProp: vi.fn().mockResolvedValue(''),
} as unknown as Page

describe('CodeQLCliTransformer links', () => {
  const transformer = new CodeQLCliTransformer()

  test.each(['free-pro-team@latest', 'enterprise-cloud@latest'])(
    'keeps links pinned to Enterprise Server on %s',
    async (currentVersion) => {
      const context = { currentVersion, currentLanguage: 'en' } as Context
      const result = await transformer.transform(stubPage, '', context)

      expect(result).toContain('# github upload-results')
      expect(result).toContain(`[SARIF support for GHES](${ghesHref})`)
    },
  )
})
