import { describe, expect, test, vi } from 'vitest'

import { GraphQLIndexTransformer } from '@/article-api/transformers/graphql-index-transformer'
import type { Context, Page } from '@/types'

vi.mock('@/article-api/lib/load-template', () => ({
  loadTemplate: () => '{{ childrenLinks }}',
}))

const makeChildPage = (title: string) =>
  ({ renderTitle: vi.fn().mockResolvedValue(title) }) as unknown as Page

const indexPage = {
  autogenerated: 'graphql',
  relativePath: 'graphql/reference/index.md',
  title: 'Reference',
  intro: '',
  children: ['/actions', '/orgs', '/sponsors'],
  renderProp: vi.fn().mockResolvedValue(''),
} as unknown as Page

describe('GraphQLIndexTransformer reference links', () => {
  const transformer = new GraphQLIndexTransformer()

  test('links children under the reference index with page titles', async () => {
    const context = {
      currentVersion: 'free-pro-team@latest',
      pages: {
        '/en/graphql/reference/actions': makeChildPage('Actions'),
        '/en/graphql/reference/orgs': makeChildPage('Organizations'),
        '/en/graphql/reference/sponsors': makeChildPage('Sponsors'),
      },
    } as unknown as Context

    const body = await transformer.transform(indexPage, '/en/graphql/reference', context)

    expect(body).toContain('[Actions](/en/graphql/reference/actions)')
    expect(body).toContain('[Organizations](/en/graphql/reference/orgs)')
    expect(body).toContain('[Sponsors](/en/graphql/reference/sponsors)')
    expect(body).not.toContain('](/actions)')
    expect(body).not.toContain('](/orgs)')
  })

  test('omits children that do not exist in the current version', async () => {
    const context = {
      currentVersion: 'enterprise-server@3.20',
      pages: {
        '/en/enterprise-server@3.20/graphql/reference/actions': makeChildPage('Actions'),
        '/en/enterprise-server@3.20/graphql/reference/orgs': makeChildPage('Organizations'),
      },
    } as unknown as Context

    const body = await transformer.transform(
      indexPage,
      '/en/enterprise-server@3.20/graphql/reference',
      context,
    )

    expect(body).toContain('[Organizations](/en/enterprise-server@3.20/graphql/reference/orgs)')
    expect(body).not.toContain('Sponsors')
  })
})
