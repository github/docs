import { describe, expect, test, vi } from 'vitest'

import { GithubAppsTransformer } from '@/article-api/transformers/github-apps-transformer'
import { getAppsData } from '@/github-apps/lib/index'
import { allVersions } from '@/versions/lib/all-versions'
import type { Context, Page } from '@/types'

vi.mock('@/github-apps/lib/index', () => ({
  getAppsData: vi.fn(),
}))

describe('GithubAppsTransformer list pages', () => {
  test('uses the rendered intro instead of the shared Page intro', async () => {
    vi.mocked(getAppsData).mockResolvedValue({
      actions: [{ slug: 'list-artifacts', verb: 'get', requestPath: '/repos/{owner}/{repo}' }],
    })

    // The shared Page instance can hold raw Liquid or HTML left over from an earlier render.
    const page = {
      autogenerated: 'github-apps',
      relativePath:
        'rest/authentication/endpoints-available-for-fine-grained-personal-access-tokens.md',
      title: 'Endpoints available for fine-grained personal access tokens',
      intro: '<p>Stale intro from another request</p>',
      markdown: '---\ntitle: Test\n---\n',
      renderProp: vi.fn().mockResolvedValue('Rendered intro'),
    } as unknown as Page

    const currentVersion = 'free-pro-team@latest'
    const context = {
      currentVersion,
      currentVersionObj: allVersions[currentVersion],
      currentLanguage: 'en',
      page,
    } as unknown as Context

    const transformer = new GithubAppsTransformer()
    const result = await transformer.transform(page, '/test', context)

    expect(result).toContain('# Endpoints available for fine-grained personal access tokens')
    expect(result).toContain('Rendered intro')
    expect(result).not.toContain('Stale intro')
    expect(result).not.toContain('<p>')
  })
})
