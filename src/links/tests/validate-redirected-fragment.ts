import { describe, expect, test, vi } from 'vitest'

import { RedirectedFragmentValidator } from '../lib/validate-redirected-fragment'
import { renderMarkdownLiquid } from '@/links/lib/extract-links'
import type { Page } from '@/types'

// headingIdsFor renders the destination page's Liquid and warms the server to do it. Stub
// both so the render-failure path can be exercised without loading the site.
vi.mock('@/links/lib/extract-links', () => ({
  renderMarkdownLiquid: vi.fn(),
}))
vi.mock('@/frame/lib/warm-server', () => ({
  default: vi.fn(async () => ({})),
}))

// A test double that overrides the (expensive, render-based) heading lookup with a fixed
// map, so the keep/drop/mixed/unvalidatable decision logic can be exercised in isolation.
class StubValidator extends RedirectedFragmentValidator {
  constructor(private idsByKey: Record<string, Set<string> | null>) {
    super({}, {}, 'en')
  }
  protected async headingIdsFor(page: Page, version: string): Promise<Set<string> | null> {
    const key = `${version}|${page.relativePath}`
    return key in this.idsByKey ? this.idsByKey[key] : new Set<string>()
  }
}

function fakePage(overrides: Partial<Page>): Page {
  return {
    relativePath: 'content/foo.md',
    applicableVersions: ['free-pro-team@latest'],
    markdown: '',
    ...overrides,
  } as unknown as Page
}

describe('RedirectedFragmentValidator.classify', () => {
  test('keep: anchor exists in every applicable version', async () => {
    const page = fakePage({
      applicableVersions: ['free-pro-team@latest', 'enterprise-cloud@latest'],
    })
    const validator = new StubValidator({
      'free-pro-team@latest|content/foo.md': new Set(['intro', 'setup']),
      'enterprise-cloud@latest|content/foo.md': new Set(['intro', 'setup']),
    })
    expect(await validator.classify(page, '#setup')).toBe('keep')
  })

  test('drop: anchor is absent from every applicable version', async () => {
    const page = fakePage({
      applicableVersions: ['free-pro-team@latest', 'enterprise-cloud@latest'],
    })
    const validator = new StubValidator({
      'free-pro-team@latest|content/foo.md': new Set(['intro']),
      'enterprise-cloud@latest|content/foo.md': new Set(['intro']),
    })
    expect(await validator.classify(page, '#setup')).toBe('drop')
  })

  test('mixed: anchor exists in some but not all versions', async () => {
    const page = fakePage({
      applicableVersions: ['free-pro-team@latest', 'enterprise-cloud@latest'],
    })
    const validator = new StubValidator({
      'free-pro-team@latest|content/foo.md': new Set(['intro', 'setup']),
      'enterprise-cloud@latest|content/foo.md': new Set(['intro']),
    })
    expect(await validator.classify(page, '#setup')).toBe('mixed')
  })

  test('unvalidatable: no destination page', async () => {
    const validator = new StubValidator({})
    expect(await validator.classify(undefined, '#setup')).toBe('unvalidatable')
  })

  test('unvalidatable: autogenerated destination page', async () => {
    const page = fakePage({ autogenerated: 'rest' })
    const validator = new StubValidator({
      'free-pro-team@latest|content/foo.md': new Set(['intro']),
    })
    expect(await validator.classify(page, '#setup')).toBe('unvalidatable')
  })

  test('unvalidatable: destination has no applicable versions', async () => {
    const page = fakePage({ applicableVersions: [] })
    const validator = new StubValidator({})
    expect(await validator.classify(page, '#setup')).toBe('unvalidatable')
  })

  test('unvalidatable: a version fails to render (never risk a destructive drop)', async () => {
    const page = fakePage({
      applicableVersions: ['free-pro-team@latest', 'enterprise-cloud@latest'],
    })
    const validator = new StubValidator({
      'free-pro-team@latest|content/foo.md': new Set(['intro']),
      // null models a render failure — must not lead to a drop.
      'enterprise-cloud@latest|content/foo.md': null,
    })
    expect(await validator.classify(page, '#setup')).toBe('unvalidatable')
  })

  test('keep: empty fragment is a no-op', async () => {
    const page = fakePage({})
    const validator = new StubValidator({
      'free-pro-team@latest|content/foo.md': new Set(),
    })
    expect(await validator.classify(page, '#')).toBe('keep')
  })

  test('keep: #top is always valid', async () => {
    // Browsers scroll to the top of the document for `#top` when nothing carries that ID,
    // so it never appears in computed heading IDs and must not be treated as stale.
    const page = fakePage({})
    const validator = new StubValidator({
      'free-pro-team@latest|content/foo.md': new Set(['intro']),
    })
    expect(await validator.classify(page, '#top')).toBe('keep')
  })

  test('handles a fragment passed without the leading hash', async () => {
    const page = fakePage({})
    const validator = new StubValidator({
      'free-pro-team@latest|content/foo.md': new Set(['setup']),
    })
    expect(await validator.classify(page, 'setup')).toBe('keep')
  })
})

describe('RedirectedFragmentValidator.headingIdsFor render failures', () => {
  test('unvalidatable, not drop, when the destination fails to render', async () => {
    // Regression guard: renderAndExtractLinks swallows Liquid failures and returns the raw
    // markdown, so heading IDs would be computed from unrendered `{% data %}` expressions.
    // Those never match a real anchor, so classify() would return 'drop' and destructively
    // delete a valid fragment. headingIdsFor must use the throwing renderer instead.
    vi.mocked(renderMarkdownLiquid).mockRejectedValueOnce(new Error('Liquid syntax error'))

    const page = fakePage({
      relativePath: 'content/bar.md',
      applicableVersions: ['free-pro-team@latest'],
      markdown: '## {% data variables.product.prodname_dotcom %} settings\n',
    })
    const validator = new RedirectedFragmentValidator({}, {}, 'en')

    expect(await validator.classify(page, '#github-settings')).toBe('unvalidatable')
  })

  test('drop still works when the destination renders cleanly', async () => {
    vi.mocked(renderMarkdownLiquid).mockResolvedValueOnce('## Intro\n')

    const page = fakePage({
      relativePath: 'content/baz.md',
      applicableVersions: ['free-pro-team@latest'],
      markdown: '## Intro\n',
    })
    const validator = new RedirectedFragmentValidator({}, {}, 'en')

    expect(await validator.classify(page, '#setup')).toBe('drop')
  })
})
